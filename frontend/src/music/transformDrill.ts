import { createDrillHiHatTrack } from "./generators/createDrillHiHats";
import type { MidiTrackInfo } from "./types";
import { detectKey } from "./analysis/detectKeys";
import { detectBassTrack } from "./analysis/detectBassTrack";
import { create808Bass } from "./generators/create808Bass";
import { add808Slides } from "./transforms/add808slides";
import { convertTrackToMinor } from "./transforms/convertToMinor";
import {
  snapshotTrack,
  type TransformationLog,
  type TransformationStage,
  type TrackChange,
} from "./transformationLog";

const isDrumTrack = (track: MidiTrackInfo) =>
  track.channel === 9 || track.instrumentFamily === "drums";
const countNotes = (tracks: MidiTrackInfo[]) =>
  tracks.reduce((sum, track) => sum + track.notes.length, 0);

export function transformToDrill(
  tracks: MidiTrackInfo[],
  bpm: number,
): MidiTrackInfo[] {
  return transformToDrillWithLog(tracks, bpm).tracks;
}

export function transformToDrillWithLog(
  tracks: MidiTrackInfo[],
  bpm: number,
  fileName = "Untitled MIDI",
): { tracks: MidiTrackInfo[]; log: TransformationLog } {
  if (!Number.isFinite(bpm) || bpm <= 0)
    throw new RangeError("Tempo must be greater than zero.");
  const key = detectKey(tracks);
  const duration = tracks.reduce(
    (end, track) =>
      track.notes.reduce(
        (latest, note) => Math.max(latest, note.time + note.duration),
        end,
      ),
    0,
  );
  const stages: TransformationStage[] = [];
  stages.push({
    id: "analysis",
    title: "Analyze input",
    status: "applied",
    description: `${tracks.length} tracks, ${countNotes(tracks)} notes, ${duration.toFixed(2)}s. Detected ${key.name} using pitch-class counts, excluding percussion. The key is an estimate. Tempo remains ${bpm} BPM.`,
    changes: [],
  });

  const tonalChanges: TrackChange[] = [];
  let shiftedNotes = 0;
  const minorTracks = tracks.map((track) => {
    if (isDrumTrack(track)) return track;
    const converted = convertTrackToMinor(track, key);
    const changed = converted.notes.filter(
      (note, index) => note.midi !== track.notes[index].midi,
    ).length;
    const renamed = converted.notes.some(
      (note, index) => note.name !== track.notes[index].name,
    );
    if (changed || renamed) {
      shiftedNotes += changed;
      tonalChanges.push({
        kind: "modified",
        sourceTrackIndex: track.trackIndex,
        before: snapshotTrack(track),
        after: snapshotTrack(converted),
      });
    }
    return converted;
  });
  stages.push({
    id: "tonality",
    title: "Rework tonality",
    status: tonalChanges.length ? "applied" : "unchanged",
    description:
      key.mode === "minor"
        ? "Input was detected as minor. The tonal conversion was skipped; pitches were preserved at this stage."
        : `${shiftedNotes} notes across ${tonalChanges.length} tracks lowered by one semitone: major thirds, sixths and sevenths relative to ${key.name.split(" ")[0]}. Timing, duration and velocity were preserved at this stage.`,
    changes: tonalChanges,
  });

  const removed = minorTracks.filter(isDrumTrack);
  let output = minorTracks.filter((track) => !isDrumTrack(track));
  stages.push({
    id: "percussion",
    title: "Remove source percussion",
    status: removed.length ? "applied" : "unchanged",
    description: `${removed.length} percussion tracks (${countNotes(removed)} notes) removed. This engine replaces all source percussion, including kicks and snares; it does not preserve those parts.`,
    changes: removed.map((track) => ({
      kind: "removed",
      sourceTrackIndex: track.trackIndex,
      before: snapshotTrack(track),
      after: null,
    })),
  });

  const hats = createDrillHiHatTrack(duration, bpm);

  hats.trackIndex =
    Math.max(-1, ...tracks.map((track) => track.trackIndex)) + 1;
  output = [...output, hats];
  stages.push({
    id: "hats",
    title: "Generate drill hi-hats",
    status: hats.notes.length ? "applied" : "skipped",
    description: `${hats.notes.length} closed hi-hats added on channel 10 at eighth-note intervals (${(30 / bpm).toFixed(3)}s). Duration 0.08s; alternating velocities 0.85 and 0.60. No kicks or snares are generated by this stage.`,
    changes: [
      {
        kind: "generated",
        sourceTrackIndex: null,
        before: null,
        after: snapshotTrack(hats),
      },
    ],
  });

  const bass = detectBassTrack(minorTracks);
  if (bass) {
    const average =
      bass.notes.reduce((sum, note) => sum + note.midi, 0) / bass.notes.length;
    const rebuilt = create808Bass(bass, bpm);
    const octaveShift = Math.round((30 - average) / 12) * 12;
    stages.push({
      id: "bass",
      title: "Rebuild 808 bass",
      status: "applied",
      description: `Selected “${bass.name}” (track ${bass.trackIndex}) because it has the lowest average MIDI pitch (${average.toFixed(1)}), excluding percussion. Shifted ${octaveShift} semitones; rebuilt ${bass.notes.length} source notes into ${rebuilt.notes.length} holds of 2–4 beats with adjacent repeated pitches merged. Velocity increases by up to 0.10. MIDI program ${rebuilt.instrumentNumber} is retained; the “808 Bass” label does not install an 808 sound in your DAW.`,
      changes: [
        {
          kind: "modified",
          sourceTrackIndex: bass.trackIndex,
          before: snapshotTrack(bass),
          after: snapshotTrack(rebuilt),
        },
      ],
    });
    const withSlides = add808Slides(rebuilt, bpm);
    const bendCount = withSlides.pitchBends?.length ?? 0;
    stages.push({
      id: "slides",
      title: "Add 808 transitions",
      status: bendCount ? "applied" : "unchanged",
      description: `${withSlides.notes.length - rebuilt.notes.length} short transition notes and ${bendCount} pitch-bend events added. Selected holds are shortened; some destination notes start early. Bends use eight interpolation steps and a ±2-semitone assumed range. Not every transition receives a slide.`,
      changes: bendCount
        ? [
            {
              kind: "modified",
              sourceTrackIndex: bass.trackIndex,
              before: snapshotTrack(rebuilt),
              after: snapshotTrack(withSlides),
            },
          ]
        : [],
    });
    output = [
      ...output.filter((track) => track.trackIndex !== bass.trackIndex),
      withSlides,
    ];
  } else {
    stages.push({
      id: "bass",
      title: "Rebuild 808 bass",
      status: "skipped",
      description:
        "No non-empty pitched track was available for bass selection.",
      changes: [],
    });
    stages.push({
      id: "slides",
      title: "Add 808 transitions",
      status: "skipped",
      description: "No bass track was available for slide generation.",
      changes: [],
    });
  }
  stages.push({
    id: "output",
    title: "Finalize arrangement",
    status: "applied",
    description: `${output.length} output tracks and ${countNotes(output)} notes. Tempo preserved at ${bpm} BPM. Full before/after track snapshots, note timing, velocities and pitch-bend values are included in the downloadable log.`,
    changes: [],
  });
  return {
    tracks: output,
    log: {
      schemaVersion: 1,
      genre: "drill",
      generatedAt: new Date().toISOString(),
      fileName,
      bpm,
      detectedKey: key,
      targetKey: key.name.replace("major", "minor"),
      sourceBassTrackIndex: bass?.trackIndex ?? null,
      stages,
      input: tracks.map(snapshotTrack),
      output: output.map(snapshotTrack),
    },
  };
}
